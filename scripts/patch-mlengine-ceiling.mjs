import fs from 'node:fs';
const path = 'electron/main/decision/MLEngine.ts';
let source = fs.readFileSync(path, 'utf8');
const baseline = '    probability = Math.min(0.96, Math.max(0.10, probability));';
const safeBaseline = `    // Uncalibrated heuristic/ML output is a ranking signal, not a guarantee.\n    // Keep it below the empirical calibration ceiling used by the journal.\n    probability = Math.min(0.95, Math.max(0.10, probability));`;
const baselineCount = source.split(baseline).length - 1;
if (baselineCount !== 1) throw new Error(`Expected one heuristic probability clamp, found ${baselineCount}`);
source = source.replace(baseline, safeBaseline);
const blended = '    probability = Math.min(0.96, Math.max(0.10, blended));';
if (!source.includes(blended)) throw new Error('Blended probability clamp not found');
source = source.replace(blended, '    probability = Math.min(0.95, Math.max(0.10, blended));');
const learned = '      learnedProbability = Math.min(0.92, Math.max(0.18, learnedProbability));';
if (!source.includes(learned)) throw new Error('Learned probability clamp not found');
source = source.replace(learned, '      learnedProbability = Math.min(0.90, Math.max(0.20, learnedProbability));');
fs.writeFileSync(path, source, 'utf8');
console.log('Patched MLEngine probability ceilings');
